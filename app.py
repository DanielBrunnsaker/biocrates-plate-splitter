ROLE_OPTIONS = [
    {"label": "Ignore",              "value": "ignore"},
    {"label": "Sample ID",           "value": "sample_id"},
    {"label": "Study ID",            "value": "study_id"},
    {"label": "Repeat Pair",         "value": "repeat_pair"},
    {"label": "Box ID",              "value": "box_id"},
    {"label": "Study Factor 1",      "value": "factor_1"},
    {"label": "Study Factor 2",      "value": "factor_2"},
    {"label": "Biological Matrix",   "value": "material"},
    {"label": "Sample Description",  "value": "sample_description"},
    {"label": "Sample Alias",        "value": "sample_alias"},
]

# Keyword groups tried in order per role, to pre-select a best-guess mapping.
# 'factor 1' / 'factor 2' are checked before the generic 'factor' fallback so an
# explicitly-numbered header wins over an ambiguous single-factor one. Likewise,
# sample_alias's specific keywords are checked before sample_id's broad "sample"
# fallback, so a "Sample Alias" header can't get claimed by sample_id first.
_ROLE_KEYWORDS: List[Tuple[str, Tuple[str, ...]]] = [
    ("sample_alias",       ("sample_alias", "sample alias", "alias")),
    ("sample_id",          ("sample_id", "sample id", "sample")),
    ("study_id",           ("study_id", "study id", "study", "sheet name", "sheet_name")),
    ("repeat_pair",        ("repeat_pair", "repeat pair", "repeat", "pair")),
    ("box_id",             ("box_id", "box id", "box", "vial box", "freezer box")),
    ("factor_1",           ("factor_1", "factor 1", "study factor 1", "biological_factor",
                             "biological factor", "factor", "group", "sex", "condition", "treatment")),
    ("factor_2",           ("factor_2", "factor 2", "study factor 2")),
    ("material",           ("material", "biological_matrix", "biological matrix", "matrix")),
    ("sample_description", ("sample_description", "sample description", "description")),
]


def _guess_column_roles(headers: List[str]) -> Dict[str, str]:
    """Best-guess {header: role} for as many headers as confidently match; headers
    with no confident match are left unmapped (default to 'ignore' in the UI)."""
    lowered = {h: h.strip().lower() for h in headers}
    used: set = set()
    roles: Dict[str, str] = {}
    for role, keywords in _ROLE_KEYWORDS:
        for kw in keywords:
            match = next((h for h in headers if h not in used and kw in lowered[h]), None)
            if match:
                roles[match] = role
                used.add(match)
                break
    return roles


def _build_mapping_section(raw: Optional[dict]) -> Optional[dbc.Card]:
    if not raw or not raw.get("columns"):
        return None
    columns = raw["columns"]
    records = raw["records"]
    guesses = _guess_column_roles(columns)

    preview_table = dash_table.DataTable(
        columns=[{"name": c, "id": c} for c in columns],
        data=records[:100],
        style_table={"overflowX": "auto", "maxHeight": "260px", "overflowY": "auto"},
        style_cell={"textAlign": "left", "padding": "4px 8px", "fontSize": "12px"},
        style_header={"fontWeight": "bold", "backgroundColor": "#e9ecef"},
    )
    preview_note = (
        f" (showing first 100 of {len(records)} rows — all {len(records)} will be loaded)"
        if len(records) > 100 else ""
    )

    mapping_rows = [
        dbc.Row([
            dbc.Col(html.Div(c, className="small fw-semibold text-truncate", title=c), width=4),
            dbc.Col(
                dcc.Dropdown(
                    id={"type": "col-role-dropdown", "index": c},
                    options=ROLE_OPTIONS,
                    value=guesses.get(c, "ignore"),
                    clearable=False,
                ),
                width=8,
            ),
        ], className="mb-1 align-items-center")
        for c in columns
    ]

    return _card(
        "Map columns before loading",
        html.P(
            f"{len(records)} row(s) parsed{preview_note}. Review the preview, then "
            "confirm or change which column is which — a likely mapping is "
            "pre-selected.",
            className="small text-muted mb-2",
        ),
        preview_table,
        html.Div(mapping_rows, className="mt-3 mb-2"),
        dbc.Row([
            dbc.Col(dbc.Button("Apply mapping — load samples", id="apply-mapping-btn",
                                color="primary", size="sm", n_clicks=0), width="auto"),
            dbc.Col(dbc.Button("Cancel", id="cancel-mapping-btn",
                                color="secondary", outline=True, size="sm", n_clicks=0),
                    width="auto"),
        ], className="g-2"),
        html.Div(id="mapping-status", className="mt-2 small"),
    )


