def _dedupe_columns(cols: List[str]) -> List[str]:
    """Keep column names unique (needed since they double as Dash component ids
    in the mapping UI) by suffixing repeats: 'Notes', 'Notes (2)', 'Notes (3)', ..."""
    seen: Dict[str, int] = {}
    out = []
    for c in cols:
        if c not in seen:
            seen[c] = 1
            out.append(c)
        else:
            seen[c] += 1
            out.append(f"{c} ({seen[c]})")
    return out


def _parse_paste_raw(text: str) -> Tuple[List[str], List[dict], str]:
    """Parse tab- or comma-separated pasted text into raw (un-mapped) records —
    role assignment happens later via the column-mapping UI."""
    lines = [l for l in text.strip().splitlines() if l.strip()]
    if not lines:
        return [], [], "Nothing to parse."

    delim = "\t" if "\t" in lines[0] else ","
    rows_raw = [[c.strip() for c in line.split(delim)] for line in lines]

    first_lower = [c.lower() for c in rows_raw[0]]
    has_header = any("sample" in c or "study" in c for c in first_lower)

    if has_header:
        headers = _dedupe_columns([c.strip() for c in rows_raw[0]])
        data_rows = rows_raw[1:]
    else:
        headers = [f"Column {i + 1}" for i in range(len(rows_raw[0]))]
        data_rows = rows_raw

    records = []
    for row in data_rows:
        if not any(c for c in row):
            continue
        records.append({h: (row[i].strip() if i < len(row) else "") for i, h in enumerate(headers)})

    if not records:
        return headers, [], "Nothing to parse."
    return headers, records, f"Parsed {len(records)} rows — map columns below."


def _parse_multi_sheet_excel_raw(xls: pd.ExcelFile) -> pd.DataFrame:
    """Combine every sheet, keeping original columns, plus a 'Sheet Name' helper
    column so Study ID can be mapped to it if the workbook is one sheet per study."""
    frames = []
    for sheet_name in xls.sheet_names:
        sheet_df = xls.parse(sheet_name)
        if sheet_df.empty:
            continue
        sheet_df = sheet_df.copy()
        sheet_df["Sheet Name"] = sheet_name.strip()
        frames.append(sheet_df)
    if not frames:
        raise ValueError("The workbook has no data in any sheet.")
    return pd.concat(frames, ignore_index=True)


def _parse_upload_raw(content: str, filename: str) -> pd.DataFrame:
    """Parse an uploaded file into a raw DataFrame with its own original column
    headers — role assignment happens later via the column-mapping UI."""
    _, b64 = content.split(",", 1)
    decoded = base64.b64decode(b64)
    if filename.lower().endswith((".xlsx", ".xls")):
        xls = pd.ExcelFile(io.BytesIO(decoded))
        if len(xls.sheet_names) > 1:
            df = _parse_multi_sheet_excel_raw(xls)
        else:
            df = xls.parse(xls.sheet_names[0])
    else:
        df = pd.read_csv(io.StringIO(decoded.decode("utf-8", errors="replace")))
    df.columns = _dedupe_columns([str(c).strip() for c in df.columns])
    return df.fillna("")


