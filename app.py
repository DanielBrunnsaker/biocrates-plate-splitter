# instead of color, so they read clearly against any study's fill: Factor 1 = white
# marker, top-left corner; Factor 2 = black marker, bottom-right corner. Shape (not
# color) carries the level within each factor, so it stays legible in this two-tone
# scheme and doesn't compete with the study color palette.
