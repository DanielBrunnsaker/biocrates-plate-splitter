@app.callback(
    Output("sample-table", "data", allow_duplicate=True),
    Output("mapping-status", "children"),
    Output("raw-import-store", "data", allow_duplicate=True),
    Input("apply-mapping-btn", "n_clicks"),
    State({"type": "col-role-dropdown", "index": ALL}, "value"),
    State({"type": "col-role-dropdown", "index": ALL}, "id"),
    State("raw-import-store", "data"),
    State("sample-table", "data"),
    prevent_initial_call=True,
)
def apply_column_mapping(_n_clicks, role_values, role_ids, raw, current_data):
    if not raw or not raw.get("records"):
        return dash.no_update, "Nothing staged to apply.", dash.no_update

    mapping = {
        rid["index"]: val for rid, val in zip(role_ids, role_values) if val and val != "ignore"
    }

    role_counts: Dict[str, int] = {}
    for role in mapping.values():
        role_counts[role] = role_counts.get(role, 0) + 1
    dupes = [r for r, c in role_counts.items() if c > 1]
    if dupes:
        dupe_labels = [o["label"] for o in ROLE_OPTIONS if o["value"] in dupes]
        return (
            dash.no_update,
            f"Each role can only be mapped to one column — duplicated: {', '.join(dupe_labels)}.",
            dash.no_update,
        )

    role_to_col = {role: col for col, role in mapping.items()}
    if "sample_id" not in role_to_col:
        return dash.no_update, "Map a column to Sample ID before applying.", dash.no_update
    if "study_id" not in role_to_col:
        return dash.no_update, "Map a column to Study ID before applying.", dash.no_update

    def get(rec: dict, role: str) -> str:
        col = role_to_col.get(role)
        return str(rec.get(col, "") or "").strip() if col else ""

    new_rows = []
    for rec in raw["records"]:
        sid = get(rec, "sample_id")
        stud = get(rec, "study_id")
        if not sid or not stud:
            continue
        new_rows.append({
            "sample_id": sid,
            "study_id": stud,
            "repeat_pair": get(rec, "repeat_pair"),
            "box_id": get(rec, "box_id"),
            "factor_1": get(rec, "factor_1"),
            "factor_2": get(rec, "factor_2"),
            "material": get(rec, "material"),
            "sample_description": get(rec, "sample_description"),
            "sample_alias": get(rec, "sample_alias"),
        })

    if not new_rows:
        return (
            dash.no_update,
            "No valid rows after mapping — every row needs a Sample ID and Study ID.",
            dash.no_update,
        )

    base = [] if raw.get("mode") == "replace" else list(current_data or [])
    return base + new_rows, f"Loaded {len(new_rows)} samples.", None


