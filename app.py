def update_table(
    file_content, _add_click, _quick_click, _paste_add, _paste_replace,
    _ex_simple, _ex_complex,
    filename, current_data, quick_study, quick_n, quick_prefix, paste_text,
    llm_upload_on, llm_paste_on, llm_model,
):
    triggered = ctx.triggered_id
    no_paste = dash.no_update
    no_raw = dash.no_update

    if triggered == "upload-data" and file_content:
        try:
            _, b64 = file_content.split(",", 1)
            decoded = base64.b64decode(b64)
            if llm_upload_on:
                if filename.lower().endswith((".xlsx", ".xls")):
                    text = llm_parser.excel_bytes_to_text(decoded)
                else:
                    text = decoded.decode("utf-8", errors="replace")
                records, msg = llm_parser.parse_with_llm(text, llm_model)
                return (records or (current_data or [])), msg, no_paste, no_raw
            df = _parse_upload_raw(file_content, filename)
            if df.empty:
                return current_data or [], "No data found in file.", no_paste, no_raw
            raw = {"columns": list(df.columns), "records": df.to_dict("records"), "mode": "replace"}
            return (
                dash.no_update,
                f"Loaded {len(df)} rows from {filename} — map columns below.",
                no_paste, raw,
            )
        except Exception as exc:
            return current_data or [], f"Error reading file: {exc}", no_paste, no_raw

    if triggered == "add-row-btn":
        data = list(current_data or [])
        data.append({
            "sample_id": "", "study_id": "", "repeat_pair": "", "box_id": "",
            "factor_1": "", "factor_2": "", "material": "", "sample_description": "",
            "sample_alias": "",
        })
        return data, dash.no_update, no_paste, no_raw

    if triggered == "quick-add-btn":
        if not quick_study or not quick_n:
            return current_data or [], "Provide Study ID and number of samples.", no_paste, no_raw
        prefix = (quick_prefix or "S").strip()
        n = int(quick_n)
        new_rows = [
            {"sample_id": f"{prefix}{i:03d}", "study_id": quick_study.strip(),
             "repeat_pair": "", "box_id": "", "factor_1": "", "factor_2": "", "material": "",
             "sample_description": "", "sample_alias": ""}
            for i in range(1, n + 1)
        ]
        return list(current_data or []) + new_rows, f"Added {n} samples for '{quick_study}'.", no_paste, no_raw

    if triggered == "ex-simple-btn":
        return SIMPLE_EXAMPLE.to_dict("records"), "Simple example loaded.", no_paste, no_raw

    if triggered == "ex-complex-btn":
        return (
            COMPLEX_EXAMPLE.to_dict("records"),
            "Complex example loaded — 440 samples, 4 studies, 14 repeat pairs. "
            "Per-study mode needs 7 plates (3+2+1+1); smart-pack mode needs 6. "
            "Tip: enable 'Balance factor' to distribute Female/Male evenly across plates.",
            no_paste, no_raw,
        )

    if triggered in ("paste-add-btn", "paste-replace-btn"):
        if not paste_text or not paste_text.strip():
            return current_data or [], dash.no_update, "Nothing pasted.", no_raw
        if llm_paste_on:
            records, msg = llm_parser.parse_with_llm(paste_text, llm_model)
            if not records:
                return current_data or [], dash.no_update, msg, no_raw
            base = [] if triggered == "paste-replace-btn" else list(current_data or [])
            return base + records, dash.no_update, msg, no_raw
        mode = "replace" if triggered == "paste-replace-btn" else "append"
        columns, records, msg = _parse_paste_raw(paste_text)
        if not records:
            return current_data or [], dash.no_update, msg, no_raw
        raw = {"columns": columns, "records": records, "mode": mode}
        return dash.no_update, dash.no_update, msg, raw

    return current_data or [], dash.no_update, no_paste, no_raw


